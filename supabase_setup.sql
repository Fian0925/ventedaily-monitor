-- Run as the database owner before deploying this version of the bot.
begin;

create table if not exists public.product_events (
    id bigint generated by default as identity primary key,
    nama text not null,
    event_type text not null,
    stock text,
    harga text,
    detected_at timestamptz not null default now()
);
create index if not exists product_events_detected_at_id_idx
    on public.product_events (detected_at desc, id desc);

create table if not exists public.user_settings (
    chat_id text primary key,
    marketplace text default 'shopee',
    admin_fee numeric default 6.5,
    markup_type text default 'percent',
    markup_value numeric default 0,
    created_at timestamptz not null default now()
);
alter table public.user_settings
    add column if not exists role text default 'user',
    add column if not exists plan_type text default 'none',
    add column if not exists valid_until timestamptz default '2000-01-01 00:00:00+00',
    add column if not exists reminder_sent text default '',
    add column if not exists referred_by text default '',
    add column if not exists referral_count integer default 0;

create table if not exists public.stock_snapshot (
    id text primary key,
    data jsonb not null,
    updated_at timestamptz not null default now()
);

create table if not exists public.subscription_plans (
    code text primary key,
    name text not null,
    plan_type text not null default 'pro',
    duration_days integer not null check (duration_days > 0),
    price integer not null check (price > 0),
    is_active boolean not null default true,
    sort_order integer not null default 100,
    updated_at timestamptz not null default now()
);

create table if not exists public.payment_requests (
    invoice text primary key,
    chat_id text not null,
    username text not null default '',
    plan_code text not null,
    plan_name text not null,
    plan_type text not null default 'pro',
    duration_days integer not null check (duration_days > 0),
    amount integer not null check (amount > 0),
    status text not null default 'pending',
    created_at timestamptz not null default now(),
    submitted_at timestamptz,
    verified_at timestamptz,
    verified_by text,
    rejected_at timestamptz
);
alter table public.payment_requests
    add column if not exists admin_notified_at timestamptz,
    add column if not exists admin_notify_claimed_at timestamptz;
create index if not exists payment_requests_admin_notify_idx
    on public.payment_requests (submitted_at)
    where status = 'waiting_verification' and admin_notified_at is null;

create table if not exists public.subscription_reminders (
    chat_id text not null,
    valid_until timestamptz not null,
    reminder_key text not null,
    primary key (chat_id, valid_until, reminder_key)
);

create table if not exists public.referral_rewards (
    referred_chat_id text primary key,
    inviter_chat_id text not null,
    bonus_days integer not null check (bonus_days > 0),
    created_at timestamptz not null default now()
);

alter table public.product_events enable row level security;
alter table public.user_settings enable row level security;
alter table public.stock_snapshot enable row level security;
alter table public.subscription_plans enable row level security;
alter table public.payment_requests enable row level security;
alter table public.subscription_reminders enable row level security;
alter table public.referral_rewards enable row level security;

-- The snapshot and its history advance together. A stale version cannot insert events.
create or replace function public.save_stock_cycle(
    p_expected_updated_at timestamptz, p_data jsonb, p_events jsonb
) returns boolean
language plpgsql set search_path = '' as $$
begin
    if p_expected_updated_at is null then
        insert into public.stock_snapshot (id, data)
        values ('latest', p_data)
        on conflict (id) do nothing;
    else
        update public.stock_snapshot
        set data = p_data, updated_at = greatest(
            pg_catalog.clock_timestamp(), updated_at + interval '1 microsecond'
        )
        where id = 'latest' and updated_at = p_expected_updated_at;
    end if;
    if not found then
        return false;
    end if;

    insert into public.product_events (nama, event_type, stock, harga)
    select item.nama, item.event_type, item.stock, item.harga
    from pg_catalog.jsonb_to_recordset(p_events)
        as item(nama text, event_type text, stock text, harga text);
    return true;
end;
$$;

create or replace function public.activate_monitor_trial(p_chat_id text)
returns timestamptz
language plpgsql set search_path = '' as $$
declare
    v_until timestamptz := now() + interval '120 hours';
begin
    update public.user_settings
    set plan_type = 'trial', valid_until = v_until, reminder_sent = ''
    where chat_id = p_chat_id
      and coalesce(role, 'user') <> 'admin'
      and coalesce(lower(btrim(plan_type)), '') in ('', 'none')
      and coalesce(nullif(valid_until::text, '')::timestamptz, '2000-01-01 00:00:00+00')
          = '2000-01-01 00:00:00+00'::timestamptz;
    if found then
        return v_until;
    end if;
    return null;
end;
$$;

-- The referred user's row lock serializes awards for the same referral.
create or replace function public.grant_monitor_referral(p_chat_id text, p_bonus_days integer)
returns text
language plpgsql set search_path = '' as $$
declare
    v_inviter text;
begin
    select referred_by into v_inviter
    from public.user_settings
    where chat_id = p_chat_id
    for update;
    if p_bonus_days <= 0 or v_inviter is null or v_inviter = p_chat_id
       or v_inviter !~ '^[0-9]+$' then
        return null;
    end if;
    if exists (select 1 from public.referral_rewards where referred_chat_id = p_chat_id) then
        return null;
    end if;

    update public.user_settings
    set valid_until = greatest(now(), nullif(valid_until::text, '')::timestamptz)
            + pg_catalog.make_interval(hours => 24 * p_bonus_days),
        referral_count = coalesce(referral_count, 0) + 1,
        reminder_sent = ''
    where chat_id = v_inviter and coalesce(plan_type, 'none') <> 'suspended';
    if not found then
        return null;
    end if;
    insert into public.referral_rewards (referred_chat_id, inviter_chat_id, bonus_days)
    values (p_chat_id, v_inviter, p_bonus_days);
    return v_inviter;
end;
$$;

-- Serialize approval by invoice and extend from the user's current expiry in SQL.
create or replace function public.approve_monitor_payment(
    p_invoice text, p_admin_id text, p_bonus_days integer
) returns jsonb
language plpgsql set search_path = '' as $$
declare
    v_payment public.payment_requests%rowtype;
    v_until timestamptz;
begin
    select * into v_payment from public.payment_requests
    where invoice = p_invoice for update;
    if not found or v_payment.status <> 'waiting_verification' then
        return null;
    end if;

    insert into public.user_settings (chat_id, plan_type, valid_until, reminder_sent)
    values (v_payment.chat_id, coalesce(nullif(v_payment.plan_type, ''), 'pro'),
            now() + pg_catalog.make_interval(hours => 24 * v_payment.duration_days), '')
    on conflict (chat_id) do update
    set plan_type = excluded.plan_type,
        valid_until = greatest(now(), nullif(user_settings.valid_until::text, '')::timestamptz)
            + pg_catalog.make_interval(hours => 24 * v_payment.duration_days),
        reminder_sent = ''
    returning valid_until into v_until;

    update public.payment_requests
    set status = 'paid', verified_at = now(), verified_by = p_admin_id
    where invoice = p_invoice;
    perform public.grant_monitor_referral(v_payment.chat_id, p_bonus_days);
    return pg_catalog.to_jsonb(v_payment) || pg_catalog.jsonb_build_object(
        'status', 'paid', 'valid_until', v_until
    );
end;
$$;

revoke execute on function public.save_stock_cycle(timestamptz, jsonb, jsonb),
    public.activate_monitor_trial(text), public.grant_monitor_referral(text, integer),
    public.approve_monitor_payment(text, text, integer)
    from public, anon, authenticated;
grant execute on function public.save_stock_cycle(timestamptz, jsonb, jsonb),
    public.activate_monitor_trial(text), public.grant_monitor_referral(text, integer),
    public.approve_monitor_payment(text, text, integer)
    to service_role;

grant select, insert, update on public.user_settings, public.stock_snapshot,
    public.product_events, public.subscription_plans, public.payment_requests,
    public.subscription_reminders, public.referral_rewards to service_role;
do $$
declare
    v_sequence text := pg_catalog.pg_get_serial_sequence('public.product_events', 'id');
begin
    if v_sequence is not null then
        execute format('grant usage on sequence %s to service_role', v_sequence);
    end if;
end;
$$;

notify pgrst, 'reload schema';
commit;
